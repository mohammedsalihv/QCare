const fs = require('fs');
const vm = require('vm');
const assert = require('node:assert/strict');
const html = fs.readFileSync('output/demos/waiting-time-walkthrough.html','utf8');
const elements = new Map();
for (const match of html.matchAll(/id="([^"]+)"/g)) elements.set(match[1], {innerHTML:'',textContent:'',handlers:{},addEventListener(name,fn){this.handlers[name]=fn;}});
elements.get('qcare-waiting-demo').querySelector = selector => { const element = elements.get(selector.slice(1)); assert(element,selector); return element; };
vm.runInNewContext(html.match(/<script>([\s\S]*?)<\/script>/)[1], {document:{getElementById:id=>elements.get(id)},window:{addEventListener(){}}});
const next = elements.get('qwd-next');
assert.match(elements.get('qwd-screen').innerHTML,/Add DOH/);
for(let i=0;i<3;i++) next.handlers.click();
assert.match(elements.get('qwd-screen').innerHTML,/75%/);
next.handlers.click(); assert.match(elements.get('qwd-screen').innerHTML,/Nothing uploaded/);
next.handlers.click(); assert.match(elements.get('qwd-screen').innerHTML,/Add DOH/);
const {getPreset,analyzeWaiting}=require('../server/utils/waitingTime');
const headers=getPreset('WT008').columns;
const rows=[10,30,45,20,null].map((minutes,i)=>{const r={record_id:`DEMO-0${i+1}`,reporting_date:'2026-07-01',population_eligible:'yes',exclusion_reason:minutes===null?'lwbs':'none',registration_at:'2026-07-01T09:00:00+04:00',doctor_at:minutes===null?'':`2026-07-01T09:${minutes}:00+04:00`};return {row:i+2,values:headers.map(h=>r[h])};});
const result=analyzeWaiting({headers,rows},'WT008','Q3',2026);
assert.equal(result.calculatedValue,75);assert.equal(result.numerator,3);assert.equal(result.denominator,4);assert.equal(result.excluded,1);assert.equal(result.waitingStatistics.mean,26.25);assert.equal(result.waitingStatistics.median,25);assert.equal(result.canSubmit,true);
console.log('Demo navigation verified; example values verified against the actual waiting-time calculator.');
