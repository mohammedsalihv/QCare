    const editPath = '/' + toEdit._id;
    const editBody = { ...payload, expectedVersion: 0, auditTitle: 'Rescheduled clinic review', auditorName: 'External reviewer', concernedPersons: [String(staff._id)], concernedDepartments: [String(department._id)], sessions: [{ startAt: '2026-12-21T13:00:00+04:00', endAt: '2026-12-21T16:00:00+04:00' }], status: 'completed', overallScore: 100 };
    assert.equal((await request(editPath, 'PUT', editBody, null)).status, 401);
    assert.equal((await request(editPath, 'PUT', editBody, staff)).status, 403);
    assert.equal((await request(editPath, 'PUT', { ...editBody, location: '' })).status, 400);
    assert.equal((await request(editPath, 'PUT', { ...editBody, expectedVersion: 99 })).status, 409);
    const updatedSchedule = await request(editPath, 'PUT', editBody);
    assert.equal(updatedSchedule.status, 200, JSON.stringify(updatedSchedule.body));
    assert.equal(updatedSchedule.body.auditTitle, editBody.auditTitle);
    assert.equal(updatedSchedule.body.status, 'pending-approval'); assert.equal(updatedSchedule.body.overallScore, null);
    assert.equal(updatedSchedule.body.scheduledDate, '2026-12-21T09:00:00.000Z');
    assert.equal(updatedSchedule.body.concernedPersons[0].employeeName, staff.employeeName);
    assert.equal(updatedSchedule.body.history.at(-1).event, 'schedule-updated');
    assert.equal(updatedSchedule.body.__v, 1);
    assert.equal((await request(editPath, 'PUT', editBody)).status, 409);
    const replacement = await Template.create({ templateName: 'Replacement', standard: 'ADHICS', governancePillar: 'clinical-risk', criteria: [{ criterionId: 'SEC-1', text: 'Security review', weight: 2 }] });
    const switched = await request(editPath, 'PUT', { ...editBody, expectedVersion: 1, templateId: String(replacement._id) });
    assert.equal(switched.status, 200); assert.equal(switched.body.standard, 'ADHICS'); assert.equal(switched.body.criteriaSnapshot[0].text, 'Security review');
    await Template.updateOne({ _id: replacement._id }, { $set: { isActive: false, 'criteria.0.text': 'Changed after scheduling' } });
    const retained = await request(editPath, 'PUT', { ...editBody, expectedVersion: 2, templateId: String(replacement._id) });
    assert.equal(retained.status, 200); assert.equal(retained.body.criteriaSnapshot[0].text, 'Security review');
    assert.equal((await request(editPath, 'DELETE', { expectedVersion: 3 })).status, 200);
    await Template.deleteOne({ _id: replacement._id });
    // Rejection is a durable event visible to requester and receiver, with a required reason.
    const rejectedRequest = (await request('', 'POST', {...payload, auditTitle:'Rejection and resubmission'})).body;
    const rejectedPath = '/' + rejectedRequest._id;
    assert.equal((await request(rejectedPath + '/schedule-approval', 'PUT', {expectedVersion:0, decision:'reject'}, quality)).status, 400);
    const rejected = await request(rejectedPath + '/schedule-approval', 'PUT', {expectedVersion:0, decision:'reject',comment:'Please revise the visit dates'}, quality);
    assert.equal(rejected.body.status, 'schedule-rejected');
    assert.equal((await request(rejectedPath + '/start','PUT',{})).status,409);
    const rejectionEvents = (await notificationRequest()).body.filter(n=>n.workflow?.recordId === rejectedRequest._id);
    const rejection = rejectionEvents.find(n=>n.workflow.status === 'Rejected');
    assert(rejection); assert.equal(rejection.workflow.reason,'Please revise the visit dates');
    assert.equal(rejection.workflow.actor.name,quality.employeeName); assert(rejection.workflow.occurredAt);
    assert.equal(rejection.workflow.requester.name,officer.employeeName);
    assert((await notificationRequest('', 'GET', manager)).body.some(n=>n._id === rejection._id));
    assert(!(await notificationRequest('', 'GET', staff)).body.some(n=>n._id === rejection._id));
    await notificationRequest('/'+rejection._id,'DELETE');
    assert((await notificationRequest('?recordId='+rejectedRequest._id+'&module=Audit%20schedule')).body.some(n=>n._id===rejection._id), 'Dismissing a notification preserves process history');
    const resubmit = await request(rejectedPath,'PUT',{...payload,expectedVersion:1});
    assert.equal(resubmit.body.status,'pending-approval'); assert.equal(resubmit.body.scheduleRejectionReason,undefined);
    assert.equal((await request(rejectedPath+'/schedule-approval','PUT',{expectedVersion:2},quality)).status,200);
    assert.equal((await request(rejectedPath,'DELETE',{expectedVersion:3})).status,200);
    const processRequest = async (route, method, body, user=staff) => {
      const response = await fetch(base + route,{method,headers:{'Content-Type':'application/json',Authorization:'Bearer '+jwt.sign({id:user._id},process.env.JWT_SECRET || 'default_secret')},body:JSON.stringify(body)});
      return {status:response.status,body:await response.json()};
    };
    const change = await processRequest('/api/qms/change-requests','POST',{title:'Review operating procedure',description:'Proposed revision',reason:'Improve process',department:'Quality'});
    assert.equal(change.status,201,JSON.stringify(change.body));
    const changePath='/api/qms/change-requests/'+change.body._id;
    assert.equal((await processRequest(changePath,'PUT',{status:'Rejected'},quality)).status,400);
    assert.equal((await processRequest(changePath,'PUT',{status:'Approved'},staff)).status,403);
    assert.equal((await processRequest(changePath,'PUT',{status:'Rejected',rejectionReason:'Add impact assessment'},quality)).status,200);
    const requesterEvents=(await notificationRequest('', 'GET', staff)).body.filter(n=>n.workflow?.recordId===change.body._id);
    assert(requesterEvents.some(n=>n.workflow.status==='Pending Approval'));
    assert(requesterEvents.some(n=>n.workflow.reason==='Add impact assessment' && n.workflow.actor.name===quality.employeeName));
    const privilege=await processRequest('/api/cp/privileges','POST',{staffId:String(staff._id),specialty:'General practice',expiryDate:'2027-10-30'});
    assert.equal(privilege.status,201,JSON.stringify(privilege.body));
    assert.equal((await processRequest('/api/cp/privileges/'+privilege.body._id+'/approve','PUT',{decision:'reject'},manager)).status,400);
    assert.equal((await processRequest('/api/cp/privileges/'+privilege.body._id+'/approve','PUT',{decision:'reject',reviewNotes:'Provide competency evidence'},manager)).body.status,'rejected');
    assert((await notificationRequest('', 'GET', staff)).body.some(n=>n.workflow?.recordId===privilege.body._id && n.workflow.reason==='Provide competency evidence'));
    const id = created.body._id;
    assert.equal(created.body.status, 'pending-approval');
    assert.equal((await request('/' + id + '/start', 'PUT', {})).status, 409);
    assert.equal((await request('/' + id + '/findings', 'PUT', { findings: [] })).status, 409);
    assert.equal((await request('/' + id + '/actions', 'POST', {})).status, 409);
    assert.equal((await request('?scope=calendar')).body.length, 0);
    const Notification = require('../models/Notification');
    const notices = await notificationRequest();
