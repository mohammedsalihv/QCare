const router = require('express').Router();
const multer = require('multer');
const { protect } = require('../middleware/authMiddleware');
const controller = require('../controllers/documentController');
const engagement = require('../controllers/documentEngagementController');
const upload = multer({ storage: multer.memoryStorage(), limits: { fileSize: 10 * 1024 * 1024, files: 1, fields: 20, fieldSize: 8000 } }).single('file');
const receive = (req, res, next) => upload(req, res, error => error ? res.status(400).json({ message: 'Upload one file, up to 10 MB.' }) : next());
router.use(protect);
router.get('/options', controller.options);
router.get('/reading-tasks', engagement.readingTasks);
router.get('/', controller.getDocuments);
router.post('/', receive, controller.addDocument);
router.get('/:id/download', controller.download);
router.put('/:id', receive, controller.updateDocument);
router.post('/:id/actions', controller.command);
router.get('/:id/reading', engagement.reading);
router.post('/:id/reading', engagement.assign);
router.post('/:id/acknowledge', engagement.acknowledge);
router.post('/:id/delegate', engagement.delegate);
router.get('/:id/feedback', engagement.feedback);
router.post('/:id/feedback', engagement.addFeedback);
router.post('/:id/feedback/:feedbackId/respond', engagement.respond);
router.post('/:id/helpful', engagement.helpful);
router.get('/:id/report/download', engagement.report);
router.delete('/:id', controller.deleteDocument);
router.put('/:id/endorse', controller.endorseDocument);
module.exports = router;
